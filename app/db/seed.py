def seed_if_empty(db_path: str | None = None) -> int:
    """若商品表为空则写入种子数据，返回商品总数。"""
    with get_conn(db_path) as conn:
        count = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
        if count == 0:
            conn.executemany(
                "INSERT INTO products (name, category, brand, price, specs, features, rating, stock, description) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                PRODUCTS,
            )
            count = len(PRODUCTS)
    return count
